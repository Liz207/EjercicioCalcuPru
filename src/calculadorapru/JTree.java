    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
         // 1. Obtener el nodo seleccionado
    String cadena = JOptionPane.showInputDialog(this, "Ingrese un departamento");
    DefaultMutableTreeNode parentNode = null;
    TreePath parentPath = jTree1.getSelectionPath();

    // 2. Si no hay selección, se usa la raíz como padre
    if (parentPath == null) {
        parentNode = Titulo; // "Titulo" es el nodo raíz
    } else {
        parentNode = (DefaultMutableTreeNode) parentPath.getLastPathComponent();
    }

    // 3. Crear y agregar el nuevo nodo
    DefaultMutableTreeNode child = new DefaultMutableTreeNode(cadena);
    modelo.insertNodeInto(child, parentNode, parentNode.getChildCount());
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnRemoverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoverActionPerformed
        // TODO add your handling code here:
         DefaultMutableTreeNode parentNode = null;
    TreePath currentSelection = jTree1.getSelectionPath();
    
    if (currentSelection != null) {
        parentNode = (DefaultMutableTreeNode) currentSelection.getLastPathComponent();
        DefaultTreeModel model = (DefaultTreeModel) jTree1.getModel();
        model.removeNodeFromParent(parentNode);
    }
    }//GEN-LAST:event_btnRemoverActionPerformed

    private void btnInformacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInformacionActionPerformed
        // TODO add your handling code here:
         DefaultMutableTreeNode node = (DefaultMutableTreeNode) jTree1.getLastSelectedPathComponent();
    
    if (node == null) { // Verifica si hay un nodo seleccionado
        JOptionPane.showMessageDialog(this, "Ningún nodo seleccionado");
        return;
    }
    
    Object nodeInfo = node.getUserObject(); // Obtiene el texto del nodo
    JOptionPane.showMessageDialog(this, nodeInfo.toString()); // Muestra el mensaje
    }//GEN-LAST:event_btnInformacionActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        // TODO add your handling code here:
         // 1. Obtener el nodo seleccionado
    DefaultMutableTreeNode node = (DefaultMutableTreeNode) jTree1.getLastSelectedPathComponent();
    
    if (node == null) { // Verificar si hay selección
        JOptionPane.showMessageDialog(this, "Ningún nodo seleccionado");
        return;
    }

    // 2. Pedir nuevo nombre (mostrando el valor actual como texto predeterminado)
    String nuevoNombre = JOptionPane.showInputDialog(
        this,
        "Ingrese el nuevo nombre:",
        node.getUserObject().toString() // Valor actual del nodo
    );

    // 3. Actualizar el nodo si se ingresó un nombre válido
    if (nuevoNombre != null && !nuevoNombre.trim().isEmpty()) {
        node.setUserObject(nuevoNombre); // Cambiar el texto
        ((DefaultTreeModel) jTree1.getModel()).nodeChanged(node); // Actualizar vista
    }
    }//GEN-LAST:event_btnModificarActionPerformed

