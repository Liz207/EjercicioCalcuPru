    private void btnAñadirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAñadirActionPerformed
        // TODO add your handling code here:
        JFileChooser fileChooser = new JFileChooser();
int result = fileChooser.showOpenDialog(null);
if (result == JFileChooser.APPROVE_OPTION) {
    String name = fileChooser.getSelectedFile().getName();
    modelo.addElement(name);
}
    }//GEN-LAST:event_btnAñadirActionPerformed

    private void listaValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_listaValueChanged
        // TODO add your handling code here:
       if (!evt.getValueIsAdjusting()) { // Evita doble ejecución
        seleccion = lista.getSelectedIndex(); // Actualiza la variable global

        if (seleccion >= 0) {
            // ► Actualiza el JLabel con el valor seleccionado (no el índice)
            String archivoSeleccionado = lista.getSelectedValue();
            etiResultado.setText("Archivo seleccionado: " + archivoSeleccionado);
        }
    }
    }//GEN-LAST:event_listaValueChanged

    private void btnRemoverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoverActionPerformed
        // TODO add your handling code here:
         if (seleccion >= 0) { // Verifica si hay un ítem seleccionado
        modelo.remove(seleccion); // Elimina del modelo
        etiResultado.setText("Archivo removido");
    } else {
        etiResultado.setText("Ningún archivo seleccionado");
    }
    }//GEN-LAST:event_btnRemoverActionPerformed

